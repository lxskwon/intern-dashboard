export type Translator = (ko: string, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): Translator {
  return (ko, vars) => {
    let s = locale === "en" ? EN[ko] ?? ko : ko;
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
      }
    }
    return s;
  };
}
